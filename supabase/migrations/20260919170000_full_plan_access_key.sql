-- 유료 전체 일정에 **열쇠**를 붙인다.
--
-- 지금은 `/plan/아이디/full` 주소를 아는 사람이면 누구나 열 수 있다.
-- 무료 초안 주소만 알면 뒤에 `/full` 을 붙여 $25 짜리 문서를 그대로 본다.
-- 특히 랜딩에 걸린 샘플 초안 네 개는 **아이디가 공개 저장소에 적혀 있어서**,
-- 그것들에 실수로 전체 일정을 만들면 그 순간 물건이 통째로 공개된다.
--
-- 회원가입이 없는 서비스라 **링크 자체가 열쇠**가 되는 방식을 쓴다.
-- 전체 일정을 만들 때 아무도 못 맞추는 값을 하나 만들어 두고,
-- 그 값이 주소에 함께 있을 때만 문서를 보여준다.
--
-- 값이 없는(null) 줄은 **열 수 없다.** 만들어진 전체 일정이 아직 하나도 없어서
-- 지금 막히는 손님은 없다. 앞으로 만들어지는 것은 전부 값을 갖는다.

alter table public.plans
  add column full_access_key text;

comment on column public.plans.full_access_key is
  '유료 전체 일정을 여는 열쇠. /plan/<id>/full?k=<이 값> 으로만 열린다. 전체 일정을 만들 때 채운다.';
