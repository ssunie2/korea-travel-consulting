/**
 * 화면에 나가는 글. **한국어와 영어를 나란히 들고 있고, 아래 한 줄이 무엇을 보여줄지 정한다.**
 *
 * ⚠️ 손님은 해외 여행객이라 **최종 언어는 영어다.**
 *    지금 한국어로 띄우는 건 선경과 뮤조가 내용을 읽고 검토하기 위해서다.
 *    **손님을 받기 전에 아래 값을 `"en"` 으로 되돌린다.** 한 글자만 고치면 된다.
 *
 * 번역본을 따로 파일로 빼지 않고 `t({ ko, en })` 처럼 **붙여서 적는 이유**가 있다.
 * 문구가 규칙 6장(예약 대행·통역 금지)에 걸리는지 양쪽을 나란히 두고 봐야 하고,
 * 떨어뜨려 놓으면 한쪽만 고쳐서 어긋나기 십상이다.
 */
export const LANG: "ko" | "en" = "ko";

/** 두 언어를 받아 지금 언어의 것을 돌려준다. 글자든 배열이든 상관없다. */
export function t<T>(pair: { ko: T; en: T }): T {
  return pair[LANG];
}
